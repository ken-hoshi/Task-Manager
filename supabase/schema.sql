-- Task Manager の DB の構造と RLS
-- 空の Supabase のプロジェクトで、SQL Editor に貼って1回だけ実行する。
-- 前提: プロジェクト作成時に「Automatically expose new tables」をオフにしている（権限は末尾の grant で与える）。
-- 守り方: どの表も「同じワークスペースのメンバーだけ」が読み書きできる。ワークスペースの作成と参加は、関数（RPC）からだけ行う。

-- ---------------------------------------------------------------
-- 表
-- ---------------------------------------------------------------

create table public.task_status (
  id smallint generated by default as identity primary key,
  status varchar not null
);

create table public.users (
  id integer generated by default as identity primary key,
  name text not null,
  email text unique,
  auth_user_id uuid unique references auth.users (id) on update cascade on delete cascade,
  created_at timestamptz not null default now()
);

create table public.workspace (
  id integer generated by default as identity primary key,
  workspace_name varchar not null,
  created_at timestamptz not null default now(),
  space_id text not null unique
);

create table public.workspace_users (
  id integer generated by default as identity primary key,
  workspace_id integer not null references public.workspace (id) on update cascade on delete cascade,
  user_id integer not null references public.users (id) on update cascade on delete cascade,
  created_at timestamptz not null default now(),
  unique (workspace_id, user_id)
);

create table public.workspace_task_genre (
  id integer generated by default as identity primary key,
  task_genre_name varchar not null,
  workspace_id integer not null references public.workspace (id) on update cascade on delete cascade,
  sort_id integer not null,
  created_at timestamptz not null default now()
);

create table public.projects (
  id integer generated by default as identity primary key,
  project_name varchar not null,
  created_at timestamptz not null default now(),
  workspace_id integer references public.workspace (id) on update cascade on delete cascade
);

create table public.small_projects (
  id integer generated by default as identity primary key,
  small_project_name varchar not null,
  details text,
  project_id integer not null references public.projects (id) on update cascade on delete cascade,
  created_at timestamptz not null default now(),
  "isFinished" boolean not null default false
);

create table public.small_project_users (
  id integer generated by default as identity primary key,
  small_project_id integer not null references public.small_projects (id) on update cascade on delete cascade,
  user_id integer not null references public.users (id) on update cascade on delete cascade,
  created_at timestamptz not null default now()
);

create table public.task_genre (
  id integer generated by default as identity primary key,
  created_at timestamptz not null default now(),
  task_genre_name varchar not null,
  start_date date not null,
  deadline_date date not null,
  small_project_id integer not null references public.small_projects (id) on update cascade on delete cascade
);

create table public.tasks (
  id integer generated by default as identity primary key,
  task_name varchar not null,
  deadline_date date not null,
  status_id integer not null default 1 references public.task_status (id),
  details text,
  assigned_user_id integer not null references public.users (id) on update cascade on delete cascade,
  created_at timestamptz not null default now(),
  start_date date not null,
  task_genre_id integer references public.task_genre (id) on delete set null,
  number_of_days numeric not null,
  result_start_date date,
  result_deadline_date date,
  number_of_result_days numeric,
  small_project_id integer references public.small_projects (id) on update cascade on delete cascade
);

create table public.task_attachments (
  id integer generated by default as identity primary key,
  task_id integer references public.tasks (id) on update cascade on delete cascade,
  -- 重複禁止: 他人のファイルと同じパスの行を足して、ストレージの権限を借りるのを防ぐ
  file_path varchar not null unique,
  uploaded_at timestamptz default now(),
  file_name varchar not null
);

create table public.small_project_attachments (
  id integer generated by default as identity primary key,
  small_project_id integer references public.small_projects (id) on update cascade on delete cascade,
  file_path varchar not null unique,
  uploaded_at timestamptz not null default now(),
  file_name varchar not null
);

create table public.wiki (
  id integer generated by default as identity primary key,
  title text not null,
  content text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  small_project_id integer not null references public.small_projects (id) on update cascade on delete cascade
);

create table public.comments (
  id integer generated by default as identity primary key,
  task_id integer not null references public.tasks (id) on update cascade on delete cascade,
  user_id integer not null references public.users (id) on update cascade on delete cascade,
  comment_text text not null,
  created_at timestamptz not null default now(),
  "isDeleted" boolean not null default false
);

create table public.mail_notifications (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users (id) on update cascade on delete cascade,
  created_at timestamptz not null default now(),
  "isRead" boolean not null default false,
  text text not null,
  workspace_id integer references public.workspace (id) on update cascade on delete cascade
);

