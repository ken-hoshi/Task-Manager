-- ---------------------------------------------------------------
-- RLS の判定に使う関数（API に出さない private スキーマに置く）
-- security definer: 関数の持ち主の権限で読み、RLS の堂々巡りを避ける
-- ---------------------------------------------------------------

create schema if not exists private;

create function private.current_user_id()
returns integer
language sql stable security definer set search_path = ''
as $$
  select id from public.users where auth_user_id = (select auth.uid())
$$;

create function private.my_workspace_ids()
returns setof integer
language sql stable security definer set search_path = ''
as $$
  select workspace_id from public.workspace_users
  where user_id = (select private.current_user_id())
$$;

create function private.workspace_of_project(p_project_id integer)
returns integer
language sql stable security definer set search_path = ''
as $$
  select workspace_id from public.projects where id = p_project_id
$$;

create function private.workspace_of_small_project(p_small_project_id integer)
returns integer
language sql stable security definer set search_path = ''
as $$
  select p.workspace_id
  from public.small_projects sp
  join public.projects p on p.id = sp.project_id
  where sp.id = p_small_project_id
$$;

-- 小プロジェクトに属さないタスクは、担当者本人だけが触れる
create function private.can_access_task(p_task_id integer)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.tasks t
    where t.id = p_task_id
      and (
        private.workspace_of_small_project(t.small_project_id) in (select private.my_workspace_ids())
        or (t.small_project_id is null and t.assigned_user_id = (select private.current_user_id()))
      )
  )
$$;

create function private.is_member(p_user_id integer, p_workspace_id integer)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.workspace_users
    where user_id = p_user_id and workspace_id = p_workspace_id
  )
$$;

-- 名前を読めるのは、自分・同じワークスペースの人・自分のワークスペースのタスクやコメントや小プロジェクトに出てくる人
-- （メンバーから外れた人も、担当のタスクや書いたコメントに名前が出せるようにする）
create function private.is_visible_user(p_user_id integer)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select p_user_id = (select private.current_user_id())
    or exists (
      select 1 from public.workspace_users wu
      where wu.user_id = p_user_id and wu.workspace_id in (select private.my_workspace_ids())
    )
    or exists (
      select 1 from public.tasks t
      where t.assigned_user_id = p_user_id
        and private.workspace_of_small_project(t.small_project_id) in (select private.my_workspace_ids())
    )
    or exists (
      select 1 from public.comments c
      join public.tasks t on t.id = c.task_id
      where c.user_id = p_user_id
        and private.workspace_of_small_project(t.small_project_id) in (select private.my_workspace_ids())
    )
    or exists (
      select 1 from public.small_project_users spu
      where spu.user_id = p_user_id
        and private.workspace_of_small_project(spu.small_project_id) in (select private.my_workspace_ids())
    )
$$;

revoke all on all functions in schema private from public;
grant usage on schema private to authenticated;
grant execute on all functions in schema private to authenticated;

