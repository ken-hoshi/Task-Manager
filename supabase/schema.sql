-- 同じ名前があれば 23505 を返す。作った人をメンバーに入れ、参加用の合言葉（space_id）を返す
create function public.create_workspace(p_workspace_name text)
returns text
language plpgsql security definer set search_path = ''
as $$
declare
  chars constant text := 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
  random_bytes bytea;
  new_space_id text;
  new_workspace_id integer;
begin
  if (select private.current_user_id()) is null then
    raise exception 'not signed in' using errcode = '42501';
  end if;
  if exists (select 1 from public.workspace where workspace_name = p_workspace_name) then
    raise exception 'workspace name already exists' using errcode = '23505';
  end if;
  loop
    -- 暗号に使える乱数（gen_random_uuid）から8文字を作る。7・9バイト目には版と種類の印が入るので、6〜9バイト目は使わない
    random_bytes := uuid_send(gen_random_uuid());
    select string_agg(substr(chars, 1 + get_byte(random_bytes, i) % 62, 1), '' order by i)
      into new_space_id
      from unnest(array[0, 1, 2, 3, 4, 5, 10, 11]) as i;
    exit when not exists (select 1 from public.workspace where space_id = new_space_id);
  end loop;
  insert into public.workspace (workspace_name, space_id) values (p_workspace_name, new_space_id)
    returning id into new_workspace_id;
  insert into public.workspace_users (workspace_id, user_id)
    values (new_workspace_id, (select private.current_user_id()));
  return new_space_id;
end;
$$;

-- 合言葉が合うワークスペースの id と名前だけを返す（メンバーでなくても引ける）
create function public.find_workspace_by_space_id(p_space_id text)
returns table (id integer, workspace_name varchar)
language sql stable security definer set search_path = ''
as $$
  select w.id, w.workspace_name
  from public.workspace w
  where w.space_id = p_space_id
    and (select private.current_user_id()) is not null
$$;

-- 合言葉の一覧で、ログイン中の人をまとめて参加させる。1つでも合わなければ、どれにも参加しない
create function public.join_workspaces(p_space_ids text[])
returns void
language plpgsql security definer set search_path = ''
as $$
declare
  me integer := (select private.current_user_id());
  found_count integer;
begin
  if me is null then
    raise exception 'not signed in' using errcode = '42501';
  end if;
  select count(*) into found_count
    from public.workspace where space_id = any (p_space_ids);
  if found_count = 0 or found_count <> cardinality(array(select distinct unnest(p_space_ids))) then
    raise exception 'workspace not found' using errcode = 'P0002';
  end if;
  insert into public.workspace_users (workspace_id, user_id)
    select id, me from public.workspace where space_id = any (p_space_ids)
    on conflict (workspace_id, user_id) do nothing;
end;
$$;

revoke all on function public.create_workspace(text) from public, anon;
revoke all on function public.find_workspace_by_space_id(text) from public, anon;
revoke all on function public.join_workspaces(text[]) from public, anon;
grant execute on function public.create_workspace(text) to authenticated;
grant execute on function public.find_workspace_by_space_id(text) to authenticated;
grant execute on function public.join_workspaces(text[]) to authenticated;

